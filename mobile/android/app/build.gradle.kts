/**
 * Where the backend is.
 *
 * `local.properties` is untracked, so every machine keeps its own address without a code
 * change: `hawraa.baseUrl=http://192.168.1.111:1407`. `-Phawraa.baseUrl=…` overrides it for a
 * one-off build (useful in CI, where `local.properties` does not exist).
 *
 * The default is the emulator's host loopback. It is deliberately **not** `localhost`:
 * `localhost` on the device is the device itself, which is the single most common way to
 * spend an hour debugging a server that is running fine.
 */
val localProperties = Properties().apply {
    val file = rootProject.file("local.properties")
    if (file.exists()) file.inputStream().use { load(it) }
}

val serverUrl: String = (
    providers.gradleProperty("hawraa.baseUrl").orNull
        ?: localProperties.getProperty("hawraa.baseUrl")
        ?: "http://10.0.2.2:1407"
    ).trimEnd('/')

