/**
 * Where mirrored audio lives, and the URL path it is served from.
 *
 * These two must agree, and the agreement is load-bearing: the mirror writes to
 * `${cwd}/uploads/recitation/<relativePath>` and Lesan's static handler serves
 * `${cwd}${url.pathname}` for any path under `/uploads`. So the public path is exactly
 * `/uploads/recitation/` + the manifest's `relativePath` — the same string the device uses
 * as its own storage path. One identity for a file, three places that must not drift.
 *
 * The root follows the **working directory** on purpose. `deno task start` is defined to run
 * from `back/`, so the mirror and the static handler always resolve to the same tree. An
 * env override would let them point at different directories and produce 404s that look like
 * a client bug, so there is no override.
 */

export const RECITATION_PUBLIC_PREFIX = "/uploads/recitation";

/** Absolute directory the mirror writes into. */
export const audioRoot = (): string => `${Deno.cwd()}/uploads/recitation`;

/** The server-relative URL a mirrored file is reachable at. */
export const publicPathOf = (relativePath: string): string =>
  `${RECITATION_PUBLIC_PREFIX}/${relativePath}`;

/**
 * Resolves a manifest `relativePath` under [root], refusing anything that escapes it.
 *
 * Written with explicit segment checks rather than `new URL("file://…")`: the URL parser
 * percent-encodes non-ASCII, and a reciter key or a path segment with a space would then
 * resolve to a name that does not exist on disk. Segment checks are also the actual rule we
 * want to enforce — no `..`, no absolute path — instead of a string-prefix side effect.
 *
 * `relativePath` is generated by `buildManifest` and is not user input, so this is defence in
 * depth rather than a live vulnerability. It costs one loop; being wrong costs writing
 * outside the audio tree from a data-driven path.
 */
export const resolveUnderRoot = (
  root: string,
  relativePath: string,
): string => {
  if (relativePath.startsWith("/")) {
    throw new Error(`relativePath must be relative: ${relativePath}`);
  }
  const segments = relativePath.split("/");
  for (const segment of segments) {
    if (segment === ".." || segment === "." || segment === "") {
      throw new Error(`relativePath has a forbidden segment: ${relativePath}`);
    }
  }
  const base = root.endsWith("/") ? root.slice(0, -1) : root;
  return `${base}/${segments.join("/")}`;
};

/** Directory part of an absolute path, without importing `std/path` for one function. */
export const dirname = (path: string): string => {
  const cut = path.lastIndexOf("/");
  return cut <= 0 ? "/" : path.slice(0, cut);
};
